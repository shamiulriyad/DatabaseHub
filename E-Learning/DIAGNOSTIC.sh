echo "Expected: Shows your JWT claims (should include 'Admin' role)"
echo ""

echo -e "${BLUE}2. Database Query${NC}"
echo "======================================"
echo ""
echo "Run this SQL query in your PostgreSQL client (pgAdmin or psql):"
echo ""
echo "-- Check all teacher applications"
echo "SELECT "
echo "  ta.\"Id\", ta.\"UserId\", ta.\"Status\", ta.\"ApplicationDate\","
echo "  u.\"Username\", u.\"Email\", u.\"FirstName\", u.\"LastName\", u.\"IsAdmin\""
echo "FROM \"TeacherApplications\" ta"
echo "JOIN \"Users\" u ON ta.\"UserId\" = u.\"Id\""
echo "ORDER BY ta.\"ApplicationDate\" DESC"
echo "LIMIT 10;"
echo ""
echo "-- Count pending applications"
echo "SELECT COUNT(*) FROM \"TeacherApplications\" WHERE \"Status\" = 'Pending';"
echo ""
