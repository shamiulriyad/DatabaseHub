#!/bin/bash

# Teacher Application Diagnostic Script
# This script will help debug why teacher applications aren't appearing in the admin panel

echo "====================================="
echo "Teacher Application Diagnostic Test"
echo "====================================="
echo ""

# Colors for output
GREEN='\033[0;32m'
RED='\033[0;31m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

# Configuration
BACKEND_URL="http://localhost:5145"
FRONTEND_URL="http://localhost:3001"

echo -e "${BLUE}1. Testing Backend API Endpoints${NC}"
echo "===================================="
echo ""

echo -e "${YELLOW}1a. Testing GET /api/teachers/applications (without filter)${NC}"
echo "Command: curl -H 'Authorization: Bearer YOUR_ADMIN_TOKEN' \"${BACKEND_URL}/api/teachers/applications\""
echo "Expected: Returns all applications (both pending and processed)"
echo ""

echo -e "${YELLOW}1b. Testing GET /api/teachers/applications?status=Pending${NC}"
