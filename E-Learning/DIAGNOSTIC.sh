echo "3. Open DevTools (F12) → Console tab"
echo "4. Check for any error messages"
echo "5. Check the Network tab to see the API response:"
echo "   - Look for request to /api/teachers/applications?status=Pending"
echo "   - Check the response body (should contain 'applications' array)"
echo ""

echo -e "${BLUE}4. Step-by-Step Debugging${NC}"
echo "======================================"
echo ""
echo "Step 1: Create a test teacher application"
echo "  - Login as a NON-ADMIN student"
echo "  - Navigate to 'Become a Teacher' page"
echo "  - Fill out and submit the form"
echo "  - You should see success message"
echo ""
echo "Step 2: Check the database"
echo "  - Run the SQL queries above"
echo "  - Verify the new application appears with Status='Pending'"
